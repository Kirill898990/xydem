function table(headers, rows, widths, o = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cell = (text, w, head, align) =>
    new TableCell({
      borders,
      width: { size: w, type: WidthType.DXA },
      verticalAlign: VerticalAlign.CENTER,
      shading: head ? { fill: 'E8F0E3', type: ShadingType.CLEAR, color: 'auto' } : undefined,
      margins: { top: 40, bottom: 40, left: 80, right: 80 },
      children: [
        new Paragraph({
          alignment: head ? AlignmentType.CENTER : align || AlignmentType.LEFT,
          spacing: { line: 240, before: 0, after: 0 },
          children: runs(text, { size: 24, bold: head || (o.boldLast && text && rows.length && false) }),
        }),
      ],
    });
  return new Table({
    width: { size: total, type: WidthType.DXA },
    columnWidths: widths,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, widths[i], true)) }),
      ...rows.map(
        (r) =>
          new TableRow({
            cantSplit: true,
            children: r.map((t, i) => cell(String(t), widths[i], false, o.align && o.align[i])),
          }),
      ),
    ],
  });
}
