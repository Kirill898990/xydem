// [[текст]] — выделить жёлтым (заменить своими данными), **текст** — жирный, __текст__ — курсив
function runs(text, base = {}) {
  const parts = String(text).split(/(\[\[.*?\]\]|\*\*.*?\*\*|__.*?__)/g).filter(Boolean);
  return parts.map((p) => {
    if (p.startsWith('[[')) {
      const inner = p.slice(2, -2);
      const b = inner.startsWith('**') && inner.endsWith('**');
      return new TextRun({ text: b ? inner.slice(2, -2) : inner, highlight: 'yellow', font: FONT, size: base.size || SZ, bold: base.bold || b });
    }
    if (p.startsWith('**')) return new TextRun({ text: p.slice(2, -2), bold: true, font: FONT, size: base.size || SZ });
    if (p.startsWith('__')) return new TextRun({ text: p.slice(2, -2), italics: true, font: FONT, size: base.size || SZ, bold: base.bold });
    return new TextRun({ text: p, font: FONT, size: base.size || SZ, bold: base.bold, italics: base.italics });
  });
}
